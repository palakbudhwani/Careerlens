import type { Job, Skill } from '@/types'

const TOOL_SKILL = /^(git|docker|aws|azure|linux|shell scripting|ci\/cd)$/i

function jobSkills(jobId: string, names: string[]): Skill[] {
  const coreCount = Math.min(3, names.length)
  return names.map((name, index): Skill => ({
    id: `${jobId}-skill-${index + 1}`,
    name,
    category: TOOL_SKILL.test(name) ? 'tool' : 'technical',
    proficiency: index < coreCount ? 4 : 3,
  }))
}

function daysSince(isoDate: string): number {
  const posted = Date.parse(`${isoDate}T00:00:00Z`)
  if (Number.isNaN(posted)) return 0
  return Math.max(0, Math.floor((Date.now() - posted) / 86_400_000))
}

