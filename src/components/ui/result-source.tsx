import { Badge } from '@/components/ui/badge'
import { cn } from '@/lib/utils'

export interface ResultSourceNoteProps {
  source?: string | null
  className?: string
}

interface SourceDetail {
  variant: 'success' | 'accent' | 'warning' | 'outline'
  explanation: string
}

const SOURCE_DETAILS: Record<string, SourceDetail> = {
  'AI-generated (Gemini)': {
    variant: 'success',
    explanation: 'Generated by the primary AI model.',
  },
  'AI-generated (Groq fallback)': {
    variant: 'accent',
    explanation:
      'The primary AI model was unavailable, so the fallback AI provider generated this result.',
  },
  'Rule-based fallback': {
    variant: 'warning',
    explanation:
      'Both AI providers were unavailable — this result was computed deterministically from your inputs. No AI was used.',
  },
  'Rule-based': {
    variant: 'outline',
    explanation: 'Deterministic check — no AI was used.',
  },
}

export function ResultSourceNote({ source, className }: ResultSourceNoteProps) {
  if (!source) return null
  const detail = SOURCE_DETAILS[source] ?? {
    variant: 'outline' as const,
    explanation: 'Provider information unavailable.',
  }

  return (
    <div
      data-testid="result-source"
      className={cn('flex flex-wrap items-center gap-2', className)}
    >
      <Badge variant={detail.variant} className="text-[10px]">
        {source}
      </Badge>
      <span className="text-[11px] leading-snug text-muted-foreground">{detail.explanation}</span>
    </div>
  )
}
